/**
 * Transactional email for owner verification.
 *
 * Provider choice is explicit and honest:
 *
 *   resend   the production provider. One REST call, an API key in Worker env,
 *            a verified sender domain. Nothing else is needed.
 *   local    a *development-only* catcher. It exists so the verification flow
 *            can be exercised end to end on a development machine, where no
 *            mail can leave the sandbox. It is refused whenever either the
 *            configured site origin or the requesting origin is not loopback,
 *            so a deployed site can never use it — a request for it there is
 *            reported as misconfiguration instead.
 *   none     nothing is configured. Sending refuses with `email_unconfigured`
 *            and the dashboard says so plainly rather than pretending.
 *
 * The code is generated by the caller (which stores only its hash) and passed
 * in here. This module never logs it and never stores it.
 */

export interface EmailEnv {
  APP_ORIGIN?: string;
  EMAIL_PROVIDER?: string;
  EMAIL_FROM?: string;
  EMAIL_REPLY_TO?: string;
  RESEND_API_KEY?: string;
  EMAIL_APP_NAME?: string;
}

export interface EmailMessage {
  to: string;
  subject: string;
  html: string;
  text: string;
}

export interface EmailSendResult {
  ok: boolean;
  provider: string;
  ref: string | null;
  error?: string;
  /**
   * Set only by the local development catcher so the caller can show the code
   * in the dashboard it was requested from. Absent for every real provider.
   */
  localCode?: string;
}

export interface EmailProvider {
  name: string;
  configured: boolean;
  localCatch: boolean;
  from: string | null;
  send(message: EmailMessage, code: string): Promise<EmailSendResult>;
}

const RESEND_ENDPOINT = 'https://api.resend.com/emails';

function appName(env: EmailEnv): string {
  return (env.EMAIL_APP_NAME ?? '').trim() || 'the arcade dashboard';
}

/** The loopback-only catcher. Never reachable from a deployed origin. */
function localProvider(): EmailProvider {
  return {
    name: 'local',
    configured: true,
    localCatch: true,
    from: 'local-catcher@localhost',
    async send(_message, code) {
      return { ok: true, provider: 'local', ref: `local-${Date.now()}`, localCode: code };
    },
  };
}

function resendProvider(env: EmailEnv): EmailProvider {
  const key = (env.RESEND_API_KEY ?? '').trim();
  const from = (env.EMAIL_FROM ?? '').trim();
  const replyTo = (env.EMAIL_REPLY_TO ?? '').trim();

  return {
    name: 'resend',
    configured: Boolean(key && from),
    localCatch: false,
    from: from || null,
    async send(message) {
      if (!key || !from) {
        return { ok: false, provider: 'resend', ref: null, error: 'email_unconfigured' };
      }
      try {
        const response = await fetch(RESEND_ENDPOINT, {
          method: 'POST',
          headers: { authorization: `Bearer ${key}`, 'content-type': 'application/json' },
          body: JSON.stringify({
            from,
            to: [message.to],
            subject: message.subject,
            html: message.html,
            text: message.text,
            ...(replyTo ? { reply_to: replyTo } : {}),
          }),
        });

        const body = (await response.json().catch(() => null)) as { id?: string; message?: string } | null;
        if (!response.ok) {
          // Status and provider message only: no key, no address, no body.
          return {
            ok: false,
            provider: 'resend',
            ref: null,
            error: `provider_error_${response.status}${body?.message ? `: ${String(body.message).slice(0, 160)}` : ''}`,
          };
        }
        return { ok: true, provider: 'resend', ref: body?.id ?? null };
      } catch (error) {
        return { ok: false, provider: 'resend', ref: null, error: `provider_unreachable: ${(error as Error).message}` };
      }
    },
  };
}

const unconfiguredProvider: EmailProvider = {
  name: 'none',
  configured: false,
  localCatch: false,
  from: null,
  async send() {
    return { ok: false, provider: 'none', ref: null, error: 'email_unconfigured' };
  },
};

function isLoopbackOrigin(origin: string): boolean {
  try {
    const { hostname, protocol } = new URL(origin);
    return protocol === 'http:' && (hostname === 'localhost' || hostname === '127.0.0.1' || hostname === '[::1]');
  } catch {
    return false;
  }
}

/**
 * Resolves the provider for one request.
 *
 * `requestOrigin` is the origin the request actually arrived on. The local
 * catcher additionally requires the *configured* site origin to be loopback, so
 * neither a spoofed host header nor a stray env var can switch a deployed site
 * onto it.
 */
export function emailProvider(env: EmailEnv, requestOrigin: string): EmailProvider {
  const requested = (env.EMAIL_PROVIDER ?? '').trim().toLowerCase();
  const loopback = isLoopbackOrigin(requestOrigin) && isLoopbackOrigin(env.APP_ORIGIN ?? '');

  if (requested === 'local') return loopback ? localProvider() : unconfiguredProvider;
  if (requested === 'none') return unconfiguredProvider;
  if (requested === 'resend') return resendProvider(env);

  // Auto: a real key wins, otherwise fall back to the catcher on localhost.
  const resend = resendProvider(env);
  if (resend.configured) return resend;
  return loopback ? localProvider() : unconfiguredProvider;
}

export function providerSummary(env: EmailEnv, requestOrigin: string): {
  name: string;
  status: 'configured' | 'unconfigured';
  localCatch: boolean;
  from: string | null;
} {
  const provider = emailProvider(env, requestOrigin);
  return {
    name: provider.name,
    status: provider.configured ? 'configured' : 'unconfigured',
    localCatch: provider.localCatch,
    from: provider.from,
  };
}

/* --------------------------------------------------------------- templates */

const PURPOSES: Record<string, { title: string; lead: string; subject: string }> = {
  login: {
    title: 'Sign in to your dashboard',
    lead: 'Use this code to finish signing in to the owner dashboard.',
    subject: 'Your dashboard sign-in code',
  },
  'password-change': {
    title: 'Confirm your password change',
    lead: 'Use this code to confirm a new password for the owner account.',
    subject: 'Confirm your password change',
  },
  'email-change': {
    title: 'Confirm this email as your authentication address',
    lead: 'Use this code to make this address the sign-in address for the owner account.',
    subject: 'Confirm your new authentication address',
  },
};

export interface VerificationTemplate {
  subject: string;
  html: string;
  text: string;
}

export function verificationEmail(env: EmailEnv, purpose: string, code: string, ttlMinutes: number): VerificationTemplate {
  const copy = PURPOSES[purpose] ?? PURPOSES.login!;
  const name = appName(env);
  const text = [
    copy.title,
    '',
    copy.lead,
    '',
    `Code: ${code}`,
    '',
    `It expires in ${ttlMinutes} minutes and can be used once.`,
    `If you did not request it, you can ignore this email — nothing changes.`,
    '',
    `— ${name}`,
  ].join('\n');

  const html = `<div style="font-family:system-ui,-apple-system,'Segoe UI',sans-serif;line-height:1.55;color:#0b0d17">
  <h1 style="font-size:18px;margin:0 0 12px">${escapeHtml(copy.title)}</h1>
  <p style="margin:0 0 16px">${escapeHtml(copy.lead)}</p>
  <p style="margin:0 0 16px;font-family:ui-monospace,SFMono-Regular,Menlo,monospace;font-size:30px;letter-spacing:6px;font-weight:700">${escapeHtml(code)}</p>
  <p style="margin:0 0 8px;color:#555">This code expires in ${ttlMinutes} minutes and can be used once.</p>
  <p style="margin:0;color:#555">If you did not request it, you can ignore this email — nothing changes.</p>
  <p style="margin:24px 0 0;color:#888;font-size:13px">${escapeHtml(name)}</p>
</div>`;

  return { subject: copy.subject, html, text };
}

/** Notice sent after a security-relevant change actually succeeded. */
export function noticeEmail(env: EmailEnv, title: string, detail: string): VerificationTemplate {
  const name = appName(env);
  const text = [title, '', detail, '', `If this was not you, secure the account immediately.`, '', `— ${name}`].join('\n');
  const html = `<div style="font-family:system-ui,-apple-system,'Segoe UI',sans-serif;line-height:1.55;color:#0b0d17">
  <h1 style="font-size:18px;margin:0 0 12px">${escapeHtml(title)}</h1>
  <p style="margin:0 0 12px">${escapeHtml(detail)}</p>
  <p style="margin:0;color:#555">If this was not you, use the recovery instructions in the dashboard and change your password immediately.</p>
  <p style="margin:24px 0 0;color:#888;font-size:13px">${escapeHtml(name)}</p>
</div>`;
  return { subject: title, html, text };
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
